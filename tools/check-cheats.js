// Quick checks for the cheat module. node tools/check-cheats.js
import { rngFrom } from '../src/logic/rng.js';
import { generateWorld } from '../src/logic/generator.js';
import { createState, startGame, nextMatchInfo, prepareMatch, myLeague } from '../src/logic/game.js';
import * as ch from '../src/logic/cheats.js';
let pass = 0, fail = 0;
const check = (n, ok, x = '') => { ok ? pass++ : fail++; console.log(`${ok ? '  ok  ' : '  FAIL'} ${n} ${x}`); };
const world = generateWorld(7, 30000, () => {});
const rng = rngFrom(7);
const st = createState({ seed: 7, worldSize: 30000, country: 'ENG', club: { name: 'T', colours: ['#c8102e', '#fff'], crest: {} } });
startGame(st, world, rng);
check('coins', ch.addCoins(st, 10000).ok && st.coins === 10000 && st.cheated === true);
const n0 = st.cards.length;
const p = ch.freePack(st, world, rng, 'gold', { elite: true });
check('guaranteed elite pack', p.pack.cards.some((c) => c.kind === 'player' && world.getPlayer(c.playerId)?.ovr >= 85 || c.isIcon), `${p.pack.cards.length} cards`);
const s = ch.signOne(st, world, rng, 'elite', 'GK');
check('sign elite GK', s.ok && world.getPlayer(s.pack.cards[0].playerId).pos === 'GK' && world.getPlayer(s.pack.cards[0].playerId).ovr >= 85);
check('sign icon', ch.signOne(st, world, rng, 'icon').ok);
check('staff', ch.giveStaff(st, rng, 'physio').ok && st.cards.some((c) => c.kind === 'staff' && c.role === 'physio'));
st.cards.find((c) => c.kind === 'player').injuredFor = 4;
ch.healAll(st);
check('heal', st.cards.filter((c) => c.kind === 'player').every((c) => c.injuredFor === 0 && c.fitness === 100));
const before = prepareMatch(st, world).home.xi[0].ovr + prepareMatch(st, world).away.xi[0].ovr;
ch.setBoost(st, 10);
const prep = prepareMatch(st, world);
const mine = prep.info.homeIsMe ? prep.home : prep.away;
check('boost raises my stats', mine.xi.every((x) => x.ovr <= 99) && mine.xi[3].ovr > 0);
ch.setBoost(st, 0);
check('play 2 matches', ch.playMatches(st, world, 2).ok && myLeague(st).matchday === 2);
check('finish season', ch.finishSeason(st, world).ok && st.season.complete && st.season.phase === 'done');
check('next season', ch.nextSeason(st, world).ok && !st.season.complete && st.season.number === 2);
check('next season from mid-season finishes the season first', ch.playMatches(st, world, 3).ok && ch.nextSeason(st, world).ok && st.season.number === 3 && st.history.length === 2);
check('state is JSON-safe', JSON.stringify(JSON.parse(JSON.stringify(st))) === JSON.stringify(st));
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
