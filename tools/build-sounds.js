// Packs src/assets/sounds/*.ogg into src/ui/soundData.js (base64 map) so the game stays one standalone file.
// node tools/build-sounds.js   (tools/build.js calls it automatically)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function buildSounds() {
  const dir = join(ROOT, 'src/assets/sounds');
  const files = readdirSync(dir).filter((f) => f.endsWith('.ogg') || f.endsWith('.mp3')).sort();
  const lines = files.map((f) => `  ${JSON.stringify(basename(f).replace(/\.(ogg|mp3)$/, ''))}: ${JSON.stringify(readFileSync(join(dir, f)).toString('base64'))},`);
  const out = `// GENERATED by tools/build-sounds.js from src/assets/sounds/*.ogg. Do not edit.\nexport const SOUND_DATA = {\n${lines.join('\n')}\n};\n`;
  writeFileSync(join(ROOT, 'src/ui/soundData.js'), out);
  return files.length;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`soundData.js: ${buildSounds()} sounds`);
}
